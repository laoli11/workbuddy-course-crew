BANNED_WORDS = ["很简单", "不用说", "大家都知道", "随便", "想跳过也行"]


def paths(n):
    ds = glob.glob(os.path.join(ROOT, f"第{n}课_*", "01_逐字稿与脚本"))
    if not ds:
        raise FileNotFoundError(f"第{n}课目录不存在")
    d = ds[0]
    return (os.path.join(d, f"第{n}课_口播稿.md"),
            os.path.join(d, f"第{n}课_TTS朗读稿.txt"))


def to_tts(md):
    """口播稿 → 纯文本朗读稿：去标题、去 markdown、去中英间空格、标点口语化。"""
    out = []
    for raw in md.split("\n"):
        l = raw.strip()
        if not l:
            out.append("")
            continue
        if l.startswith("#") or l.startswith(">") or l.startswith("|"):
            continue
        l = l.replace("**", "").replace("`", "")
        l = l.replace("：", "，").replace("——", "，").replace("—", "，")
        # 成对引号：前引号变停顿，后引号去掉
        l = re.sub(r'["“]([^"”]*)["”]', r"，\1", l)
        l = l.replace('"', "").replace('“', "").replace('”', "")
        l = l.replace('「', "，").replace('」', "")
        l = re.sub(r"(?<=[\u4e00-\u9fff])\s+(?=[A-Za-z0-9])", "", l)
        l = re.sub(r"(?<=[A-Za-z0-9])\s+(?=[\u4e00-\u9fff])", "", l)
        l = re.sub(r"\s+", " ", l).strip()
        out.append(l)
    # 压缩连续空行
    res = []
    for l in out:
        if l == "" and (not res or res[-1] == ""):
            continue
        res.append(l)
    while res and res[-1] == "":
        res.pop()
    return "\n".join(res) + "\n"


def main():
    dry = "--dry" in sys.argv
    errors, report = [], []

    for n in LESSONS:
        md_path, tts_path = paths(n)
        md = open(md_path, encoding="utf-8").read()
        changes = []

        # 1) 禁用词
        for old, new in BANNED:
            if old in md:
                md = md.replace(old, new)
                changes.append("禁用词: " + old[:14])

        # 2) 开场钩子（幂等：标记句已在文中则跳过）
        if n in HOOKS:
            anchor, hook = HOOKS[n]
            marker = hook.split("\n")[0]
            cnt = md.count(anchor)
            if cnt != 1:
                errors.append(f"第{n}课 开场锚点命中 {cnt} 次（应为 1）：{anchor[:20]}")
            elif marker not in md:
                md = md.replace(anchor, anchor + "\n\n" + hook, 1)
                changes.append("开场钩子")

        # 3) 结尾（幂等：以「最后给你留一个小任务」判断）
        if n in ENDINGS:
            ending = ENDINGS[n]
            if "最后给你留一个小任务。" not in md:
                idx = md.rfind("## 结尾")
                if idx < 0:
                    errors.append(f"第{n}课 找不到 ## 结尾")
                else:
                    md = md[:idx] + ending
                    changes.append("结尾三件套")

        # 4) 自检
        banned_hit = [w for w in BANNED_WORDS if w in md]
        has_hook = any(k in md for k in
                       ("这节课解决什么问题", "我们解决一个问题", "这节课学完"))
        has_task = "最后给你留一个小任务。" in md
        has_rule = "记住一句话" in md
        report.append((n, has_hook, has_task, has_rule, banned_hit, len(changes)))

        if not dry:
            with open(md_path, "w", encoding="utf-8") as f:
                f.write(md)
            with open(tts_path, "w", encoding="utf-8") as f:
                f.write(to_tts(md))

    print("课 | 钩子 | 小任务 | 记住 | 禁用词残留 | 本轮改动数")
    for n, h, t, r, b, c in report:
        btxt = "、".join(b) if b else "无"
        print(f" {n} |  {'√' if h else '×'}   |   {'√' if t else '×'}    |  {'√' if r else '×'}   | {btxt:<10} | {c}")

    if errors:
        print("\n[错误] 锚点校验未通过：")
        for e in errors:
            print("  -", e)
        return 1
    print("\n锚点校验全部通过；" + ("仅试运行，未写文件" if dry else "已写入 7 门课口播稿 + TTS 朗读稿"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
